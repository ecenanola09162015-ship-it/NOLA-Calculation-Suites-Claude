const fmt = (n: number | null | undefined, p = 2) =>
  n === null || n === undefined || !Number.isFinite(n)
    ? "—"
    : n.toLocaleString("en-US", {
        minimumFractionDigits: p,
        maximumFractionDigits: p,
      });

function Numeric({
  label,
  value,
  onChange,
  unit = "mm",
  step = "any",
  title,
}: {
  label: string;
  value: number;
  onChange: (n: number) => void;
  unit?: string;
  step?: string;
  title?: string;
}) {
  return (
    <label className="slabNumeric" title={title}>
      <span>
        {label} {unit && <small>({unit})</small>}
      </span>
      <input
        type="number"
        step={step}
        value={Number.isFinite(value) ? value : ""}
        onChange={(e) =>
          onChange(e.target.value === "" ? NaN : Number(e.target.value))
        }
      />
    </label>
  );
}
function Check({
  label,
  checked,
  onChange,
  title,
}: {
  label: string;
  checked: boolean;
  onChange: (b: boolean) => void;
  title?: string;
}) {
  return (
    <label className="bpCheck" title={title}>
      <input
        type="checkbox"
        checked={checked}
        onChange={(e) => onChange(e.target.checked)}
      />{" "}
      {label}
    </label>
  );
}
/** Drawing markup, or "" if the geometry cannot be drawn. */
